def generate_realistic_target(row):
    monthly_inc = row['monthly_income']
    # Komponen aktual dari data
    needs_actual = (row['total_expense'] - row['lifestyle_expense']) / monthly_inc
    needs_actual = np.clip(needs_actual, 0.1, 0.7)
    wants_actual = row['lifestyle_burden']
    savings_actual = row['saving_ratio']
    if row['expense_ratio'] > 0.5:
        needs_target = np.clip(0.45 + np.random.uniform(-0.05, 0.05), 0.4, 0.5)
        wants_target = np.clip(0.25 + np.random.uniform(-0.05, 0.05), 0.2, 0.3)
        savings_target = 1 - needs_target - wants_target

    # Aturan adaptif berdasarkan profil keuangan
    if row['saving_ratio'] > 0.4:   # Tabungan dominan
        savings_target = np.clip(row['saving_ratio'], 0.4, 0.6)
        needs_target = max(0.15, needs_actual)
        wants_target = 1 - savings_target - needs_target
        if wants_target < 0.1:
            wants_target = 0.1
            savings_target = 1 - needs_target - wants_target
    elif row['lifestyle_burden'] > 0.3:  # Keinginan dominan
        wants_target = np.clip(row['lifestyle_burden'], 0.35, 0.5)
        needs_target = max(0.2, needs_actual)
        savings_target = 1 - wants_target - needs_target
        if savings_target < 0.1:
            savings_target = 0.1
            needs_target = 1 - wants_target - savings_target
    else:   # Kebutuhan dominan
        needs_target = np.clip(needs_actual, 0.4, 0.5)
        wants_target = max(0.1, wants_actual)
        savings_target = 1 - needs_target - wants_target
        if savings_target < 0.1:
            savings_target = 0.1
            wants_target = 1 - needs_target - savings_target

    # Normalisasi akhir
    total = needs_target + wants_target + savings_target
    needs = needs_target / total
    wants = wants_target / total
    savings = savings_target / total
    return np.array([needs, wants, savings], dtype=np.float32)

