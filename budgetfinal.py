# 8. INFERENSI DENGAN POST-PROCESSING (Rule ringan)

def apply_post_processing(allocation_pct):
    """
    Memastikan alokasi tetap masuk akal: kebutuhan 15-60%, tabungan 10-70%, total 100%.
    """
    needs, wants, savings = allocation_pct
    needs = np.clip(needs, 15, 60)
    savings = np.clip(savings, 10, 70)
    wants = 100 - needs - savings
    if wants < 5:
        wants = 5
        savings = 100 - needs - wants
    return [needs, wants, savings]

def predict_smart_budget(user_data, model, scaler, apply_rule=True):
    income = user_data.get('income', 1)
    monthly_inc = income / 12.0
    total_exp = user_data.get('total_expense', 0)
    lifestyle = user_data.get('lifestyle_expense', 0)
    loan_rate = user_data.get('loan_int_rate', 10.0)
    credit = user_data.get('credit_score', 579)
    family = user_data.get('family_size', 2)
    age = user_data.get('age', 30)

    expense_ratio = np.clip(total_exp / (monthly_inc + 1e-6), 0, 1)
    features = np.array([[
        np.log1p(income),
        expense_ratio,
        np.clip(lifestyle / (monthly_inc + 1e-6), 0, 1),
        loan_rate / 20.0,
        (credit - 300) / 549.0,
        family,
        age
    ]], dtype=np.float32)

    features_scaled = scaler.transform(features)
    preds = model.predict(features_scaled, verbose=0)[0] * 100
    preds_list = preds.tolist()

    if apply_rule:
        preds_list = apply_post_processing(preds_list)

    return {
        'kebutuhan': round(preds_list[0], 1),
        'keinginan': round(preds_list[1], 1),
        'tabungan': round(preds_list[2], 1),
        'alokasi': f"{preds_list[0]:.1f}% / {preds_list[1]:.1f}% / {preds_list[2]:.1f}%"
    }


