class FinancialAttentionLayer(layers.Layer):
    def __init__(self, units=128, temperature=1.5, dropout_rate=0.2, **kwargs):
        super().__init__(**kwargs)
        self.units = units
        self.temperature = temperature
        self.dropout_rate = dropout_rate

    def build(self, input_shape):
        n = input_shape[-1]
        self.attn_w = self.add_weight(name='attn_w', shape=(n, n), initializer='glorot_uniform')
        self.attn_b = self.add_weight(name='attn_b', shape=(n,), initializer='zeros')
        self.proj_w = self.add_weight(name='proj_w', shape=(n, self.units), initializer='glorot_uniform')
        self.proj_b = self.add_weight(name='proj_b', shape=(self.units,), initializer='zeros')
        self.dropout = layers.Dropout(self.dropout_rate)
        super().build(input_shape)

    def call(self, inputs, training=False):
        scores = (tf.matmul(inputs, self.attn_w) + self.attn_b) / self.temperature
        weights = tf.nn.softmax(scores, axis=-1)
        attended = inputs * weights
        out = tf.nn.swish(tf.matmul(attended, self.proj_w) + self.proj_b)
        return self.dropout(out, training=training)

    def get_config(self):
        cfg = super().get_config()
        cfg.update({'units': self.units, 'temperature': self.temperature, 'dropout_rate': self.dropout_rate})
        return cfg

class WeightedCategoricalCrossentropy(keras.losses.Loss):
    def __init__(self, name='weighted_categorical_crossentropy', **kwargs):
        super().__init__(name=name, **kwargs)

    def call(self, y_true, y_pred, sample_weight=None):
        y_true = tf.cast(y_true, tf.float32)
        y_pred = tf.cast(y_pred, tf.float32)
        loss = -tf.reduce_sum(y_true * tf.math.log(y_pred + 1e-7), axis=-1)
        if sample_weight is not None:
            loss = loss * tf.cast(sample_weight, tf.float32)
        return tf.reduce_mean(loss)

class SmartBudgetMonitor(keras.callbacks.Callback):
    def __init__(self, X_val, y_val, every_epoch=5):
        super().__init__()
        self.X_val = X_val
        self.y_val = y_val
        self.every = every_epoch

    def on_epoch_end(self, epoch, logs=None):
        if (epoch + 1) % self.every == 0:
            preds = self.model.predict(self.X_val, verbose=0)
            mae_needs = np.mean(np.abs(preds[:, 0] - self.y_val[:, 0]))
            mae_wants = np.mean(np.abs(preds[:, 1] - self.y_val[:, 1]))
            mae_savings = np.mean(np.abs(preds[:, 2] - self.y_val[:, 2]))
            print(f"\n[Epoch {epoch+1}] MAE: Needs={mae_needs:.4f}, Wants={mae_wants:.4f}, Savings={mae_savings:.4f}")


# 5. ARSITEKTUR MODEL

def build_smart_budget_model(n_features=7):
    inp = keras.Input(shape=(n_features,), name='financial_features')
    x = FinancialAttentionLayer(units=128, temperature=1.5, dropout_rate=0.2)(inp)
    x = layers.Dense(256, activation='relu')(x)
    x = layers.BatchNormalization()(x)
    x = layers.Dropout(0.3)(x)
    x = layers.Dense(128, activation='relu')(x)
    x = layers.BatchNormalization()(x)
    x = layers.Dropout(0.2)(x)
    output = layers.Dense(3, activation='softmax', name='smart_output')(x)
    model = Model(inputs=inp, outputs=output, name='SmartBudget_Adaptive')
    return model

